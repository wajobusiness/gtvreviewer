import React from "react";
import Link from "next/link";
import { getAllReports } from "@/lib/reports";
import { ReportCard } from "@/components/ReportCard";
import { FileText, Sparkles, FolderSync } from "lucide-react";

export default async function ReportsIndexPage() {
  const reportsData = await Promise.resolve(getAllReports());
  const reports = Array.isArray(reportsData) ? reportsData : [];

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-800">
        <div>
          <h1 className="text-2xl font-extrabold text-foreground tracking-tight flex items-center gap-2.5">
            <FileText className="w-6 h-6 text-blue-400" />
            Audit Reports Repository
          </h1>
          <p className="text-xs text-muted-foreground mt-1">
            All dynamically compiled markdown reports generated by the forensic audit engine.
          </p>
        </div>

        <div className="flex items-center gap-2 text-xs font-mono text-slate-400 bg-slate-900/60 border border-slate-800 px-3 py-1.5 rounded-lg">
          <FolderSync className="w-3.5 h-3.5 text-blue-400 animate-spin-slow" />
          <span>Reports Available: {reports.length}</span>
        </div>
      </div>

      {reports.length === 0 ? (
        <div className="rounded-2xl border border-dashed border-slate-800 bg-slate-900/30 p-12 text-center max-w-xl mx-auto my-8 space-y-4">
          <div className="w-12 h-12 rounded-full bg-blue-500/10 text-blue-400 mx-auto flex items-center justify-center">
            <FileText className="w-6 h-6" />
          </div>
          <h3 className="text-base font-bold text-foreground">No Audit Reports Generated Yet</h3>
          <p className="text-xs text-muted-foreground leading-relaxed">
            Upload your candidate evidence documents to run an automated AI forensic audit and automatically compile official UKVI-aligned Markdown reports.
          </p>
          <div className="pt-2">
            <Link
              href="/upload"
              className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-blue-600 hover:bg-blue-500 text-white text-xs font-semibold shadow-lg shadow-blue-500/20 transition-all"
            >
              <Sparkles className="w-4 h-4" />
              <span>Create New Analysis</span>
            </Link>
          </div>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
          {reports.map((report, idx) => (
            <ReportCard key={report.slug} report={report} delay={idx * 0.05} />
          ))}
        </div>
      )}
    </div>
  );
}
